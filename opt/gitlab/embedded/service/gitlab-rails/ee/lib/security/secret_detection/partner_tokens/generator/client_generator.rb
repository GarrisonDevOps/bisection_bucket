# frozen_string_literal: true

module Security
  module SecretDetection
    module PartnerTokens
      module Generator
        # Turns a reviewed VendorDefinition into ADR-006-conformant Ruby source: a
        # verifier client and its spec. The generated client always:
        #   - maps only explicitly-declared HTTP codes,
        #   - falls through to :unknown (never :inactive),
        #   - raises RateLimitError / NetworkError for the codes the vendor definition
        #     marks as such.
        #
        # The output is deterministic and reviewable, so a human still approves
        # every generated verifier before it ships. The AI's job is only to
        # produce the *data* (VendorDefinition) from the vendor docs.
        class ClientGenerator
          # A longer quoted sample pushes `let(:valid_token)` past the 120-column limit,
          # and rubocop -a cannot split a string literal, so it is emitted in chunks.
          # 94 is 120 minus the 26 characters of `  let(:valid_token) { "" }`, quotes included.
          MAX_INLINE_SAMPLE_TOKEN = 94
          SAMPLE_TOKEN_CHUNK = /.{1,80}/

          RATE_LIMIT = :rate_limit
          NETWORK_ERROR = :network_error

          CLIENT_DIR = 'ee/lib/security/secret_detection/partner_tokens'
          SPEC_DIR = 'ee/spec/lib/security/secret_detection/partner_tokens'

          def initialize(vendor_definition)
            @definition = vendor_definition
          end

          def client_source
            <<~RUBY
              # frozen_string_literal: true

              module Security
                module SecretDetection
                  module PartnerTokens
                    # Auto-generated by ClientGenerator from a reviewed VendorDefinition.
                    # #{@definition.doc_url.present? ? "Vendor docs: #{@definition.doc_url}" : 'The definition provided no vendor doc URL.'}
                    # Regenerate rather than hand-editing; keep the VendorDefinition as the source of truth.
                    class #{@definition.class_name} < BaseClient
              #{class_body_source.indent(8)}
                    end
                  end
                end
              end
            RUBY
          end

          # Just the constants + method definitions that live inside the class
          # body. Shared by client_source and by tests that eval the body into an
          # anonymous subclass of BaseClient.
          def class_body_source
            <<~RUBY.chomp
              #{endpoint_constant}

              private

              def partner_name
                #{@definition.partner_name.downcase.inspect}
              end

              #{verify_partner_token_method}

              #{'# nil means this host does not know the token, so the next host decides.' if @definition.multi_host?}
              def analyze_response(response)
                case response.code.to_i
                #{when_branches}
                else
                  # unknown-never-inactive: unmapped codes are never treated as dead tokens.
                  token_response(:unknown)
                end
              end
            RUBY
          end

          def client_path
            "#{CLIENT_DIR}/#{@definition.class_name.underscore}.rb"
          end

          def spec_path
            "#{SPEC_DIR}/#{@definition.class_name.underscore}_spec.rb"
          end

          def registry_entry
            <<~RUBY.chomp
              #{@definition.token_type.inspect} => {
                client_class: ::Security::SecretDetection::PartnerTokens::#{@definition.class_name},
                rate_limit_key: :#{@definition.rate_limit_key},
                enabled: true,
                enabled_targets: [Scanners::GSS].freeze
              }.freeze
            RUBY
          end

          def spec_source
            active_code = code_for(:active)
            inactive_code = code_for(:inactive)
            rate_limit_code = code_for(:rate_limit)
            network_error_code = code_for(:network_error)
            unknown_code = code_for(:unknown)

            <<~RUBY
              # frozen_string_literal: true

              require 'spec_helper'

              # Auto-generated by ClientGenerator. Exercises the generated verifier
              # against the guardrails every partner client must satisfy.
              RSpec.describe Security::SecretDetection::PartnerTokens::#{@definition.class_name}, feature_category: :secret_detection do
                let(:client) { described_class.new }
                #{valid_token_let}
                let(:response) { instance_double(Net::HTTPResponse) }

                it_behaves_like 'a partner token client', http_method: :#{@definition.http_method}

                #{stub_host_helper}

                describe '#verify_token' do
                  #{active_code ? "context 'when the vendor reports the token active' do\n      before do\n        allow(response).to receive_messages(code: '#{active_code}', body: '{}')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns active' do\n        expect(client.verify_token(valid_token).active?).to be(true)\n      end#{host_count_example('does not try the next host', 'once')}\n    end" : '# no active mapping declared'}

                  #{inactive_code ? "context 'when the vendor reports the token inactive' do\n      before do\n        allow(response).to receive_messages(code: '#{inactive_code}', body: '{}')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns inactive' do\n        expect(client.verify_token(valid_token).inactive?).to be(true)\n      end#{host_count_example('tries every host first', 'exactly(described_class::API_ENDPOINTS.size).times')}\n    end" : '# no inactive mapping declared'}

                  #{rate_limit_code ? "context 'when the vendor rate limits the request' do\n      before do\n        allow(response).to receive_messages(code: '#{rate_limit_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'raises RateLimitError' do\n        expect { client.verify_token(valid_token) }.to raise_error(described_class::RateLimitError)\n      end\n    end" : '# no rate_limit mapping declared'}

                  #{network_error_code ? "context 'when the vendor reports a service error' do\n      before do\n        allow(response).to receive_messages(code: '#{network_error_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'raises NetworkError' do\n        expect { client.verify_token(valid_token) }.to raise_error(described_class::NetworkError)\n      end\n    end" : '# no network_error mapping declared'}

                  #{unknown_code ? "context 'when the vendor maps a code to unknown' do\n      before do\n        allow(response).to receive_messages(code: '#{unknown_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns unknown' do\n        expect(client.verify_token(valid_token).unknown?).to be(true)\n      end\n    end" : '# no explicit unknown mapping declared'}

                  #{additional_status_contexts}

                  #{extra_headers_example}

                  #{auth_prefix_example}

                  #{multi_host_examples}

                  context 'with an unmapped response code' do
                    before do
                      allow(response).to receive_messages(code: '#{unmapped_code}', body: '')
                      allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)
                    end

                    it 'returns unknown, never inactive' do
                      result = client.verify_token(valid_token)

                      expect(result.unknown?).to be(true)
                    end
                  end

                end
              end
            RUBY
          end

          private

          def endpoint_constant
            return "API_ENDPOINT = #{@definition.endpoint.inspect}" unless @definition.multi_host?

            <<~RUBY.chomp
              # Separate regional stacks: a live token gets the dead code on every host but its own.
              API_ENDPOINTS = [
                #{@definition.endpoints.map(&:inspect).join(",\n")}
              ].freeze
            RUBY
          end

          def verify_partner_token_method
            request = <<~RUBY.chomp
              response = make_request(
                #{@definition.multi_host? ? 'endpoint' : 'API_ENDPOINT'},
                method: :#{@definition.http_method},
                headers: #{headers_literal}
              )
            RUBY

            if @definition.multi_host?
              <<~RUBY.chomp
                def verify_partner_token(token_value)
                  API_ENDPOINTS.each do |endpoint|
                    #{request}
                    result = analyze_response(response)
                    return result if result
                  end

                  token_response(:inactive)
                end
              RUBY
            else
              <<~RUBY.chomp
                def verify_partner_token(token_value)
                  #{request}
                  analyze_response(response)
                end
              RUBY
            end
          end

          # Emits case/when branches. Indentation is normalised by RuboCop
          # autocorrect after the file is written, so here we only need
          # syntactically-correct lines joined together. Codes sharing an
          # outcome collapse into one `when` list: separate branches with
          # identical bodies trip Lint/DuplicateBranch, which -a cannot fix.
          def when_branches
            @definition.compiled_status_map
              .group_by { |_code, outcome| outcome }
              # Explicitly-unknown codes fall through to else: a `when` of their
              # own would duplicate its body and trip Lint/DuplicateBranch.
              .reject { |outcome, _pairs| outcome == :unknown }
              .map do |outcome, pairs|
                codes = pairs.map(&:first).join(', ')

                "when #{codes}\n#{body_for(outcome)}"
              end
              .join("\n")
          end

          def body_for(outcome)
            case outcome
            when RATE_LIMIT
              "raise RateLimitError, \"#{double_quote_safe(@definition.partner_name)} rate limited: \#{response.code}\""
            when NETWORK_ERROR
              "raise NetworkError, \"#{double_quote_safe(@definition.partner_name)} service error: \#{response.code}\""
            when :inactive
              @definition.multi_host? ? 'nil' : 'token_response(:inactive)'
            else
              "token_response(:#{outcome})"
            end
          end

          # VendorDefinition already rejects quotes and backslashes in every embedded
          # field; this keeps the emission locally safe even if that gate drifts,
          # the same way API_ENDPOINT and valid_token go through #inspect.
          def double_quote_safe(str)
            str.inspect[1..-2]
          end

          def valid_token_let
            token = @definition.sample_token
            return "let(:valid_token) { #{token.inspect} }" if token.inspect.length <= MAX_INLINE_SAMPLE_TOKEN + 2

            chunks = token.scan(SAMPLE_TOKEN_CHUNK).map(&:inspect)
            "let(:valid_token) do\n  #{chunks.join(" \\\n    ")}\nend"
          end

          def headers_literal
            entries = [auth_header_entry, *extra_header_entries, "'Accept' => 'application/json'"]
            one_line = @definition.extra_headers.empty? && @definition.auth_prefix.nil? && !basic_auth?
            return "{ #{entries.join(', ')} }" if one_line

            # The basic auth pair, an auth prefix or any extra header can push the hash past
            # the line limit, and the rake task's rubocop -a split would then break
            # generated_client_sync_spec.rb, so these go one header per line.
            "{\n#{entries.join(",\n")}\n}"
          end

          def basic_auth?
            %w[basic_username basic_password].include?(@definition.auth_style)
          end

          def auth_header_entry
            case @definition.auth_style
            when 'bearer'
              "'Authorization' => \"Bearer \#{token_value}\""
            when 'header'
              "#{@definition.auth_param.inspect} => #{header_value}"
            when 'basic_username'
              basic = '"Basic #{Base64.strict_encode64("#{token_value}:")}"'
              "'Authorization' => #{basic}"
            when 'basic_password'
              # auth_param is the fixed basic-auth username; blank emits ':token'
              # for vendors that ignore the username (e.g. Azure DevOps).
              username = double_quote_safe(@definition.auth_param.to_s)
              basic = "\"Basic \#{Base64.strict_encode64(\"#{username}:\#{token_value}\")}\""
              "'Authorization' => #{basic}"
            else
              # VendorDefinition validates auth_style, but interpolating nil here would
              # emit syntactically invalid Ruby; fail at generation time instead.
              raise ArgumentError, "unsupported auth_style: #{@definition.auth_style.inspect}"
            end
          end

          def header_value
            return 'token_value' if @definition.auth_prefix.nil?

            "\"#{double_quote_safe(@definition.auth_prefix)}\#{token_value}\""
          end

          def extra_header_entries
            @definition.extra_headers.map { |name, value| "#{name.inspect} => #{value.inspect}" }
          end

          def code_for(outcome)
            @definition.compiled_status_map.find { |_code, mapped| mapped == outcome }&.first
          end

          def codes_for(outcome)
            @definition.compiled_status_map.filter_map { |code, mapped| code if mapped == outcome }
          end

          # spec_source tests the first code of each status outcome; each further code
          # gets its own context, so dropping it from its `when` list fails the spec.
          def additional_status_contexts
            %i[active inactive unknown].flat_map do |outcome|
              codes_for(outcome).drop(1).map { |code| status_context(code, outcome) }
            end.join("\n")
          end

          def status_context(code, outcome)
            <<~RUBY
              context 'when the vendor returns #{code}' do
                before do
                  allow(response).to receive_messages(code: '#{code}', body: '')
                  allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)
                end

                it 'returns #{outcome}' do
                  expect(client.verify_token(valid_token).#{outcome}?).to be(true)
                end
              end
            RUBY
          end

          def extra_headers_example
            return '' if @definition.extra_headers.empty?

            http_method = @definition.http_method
            # make_request passes body: on POST only, so the keyword arguments differ.
            body = http_method == 'post' ? ', body: anything' : ''

            # One header per line, as in headers_literal, so no line passes the limit
            # and gets split by rubocop -a.
            <<~RUBY
              it 'sends the extra headers' do
                expected_headers = {
                #{extra_header_entries.join(",\n")}
                }
                allow(response).to receive_messages(code: '#{code_for(:active)}', body: '{}')
                allow(Integrations::Clients::HTTP).to receive(:#{http_method}).and_return(response)

                client.verify_token(valid_token)

                expect(Integrations::Clients::HTTP).to have_received(:#{http_method})
                  .with(anything, headers: hash_including(expected_headers)#{body})
              end
            RUBY
          end

          def auth_prefix_example
            return '' if @definition.auth_prefix.nil?

            http_method = @definition.http_method
            body = http_method == 'post' ? ', body: anything' : ''
            prefix = double_quote_safe(@definition.auth_prefix)

            # The expected header gets its own line so the .with line stays within the limit.
            <<~RUBY
              it 'sends the auth prefix' do
                expected_header = { #{@definition.auth_param.inspect} => "#{prefix}\#{valid_token}" }
                allow(response).to receive_messages(code: '#{code_for(:active)}', body: '{}')
                allow(Integrations::Clients::HTTP).to receive(:#{http_method}).and_return(response)

                client.verify_token(valid_token)

                expect(Integrations::Clients::HTTP).to have_received(:#{http_method})
                  .with(anything, headers: hash_including(expected_header)#{body})
              end
            RUBY
          end

          # Rides inside the active and inactive contexts, which already stub every host alike.
          def host_count_example(title, count)
            return '' unless @definition.multi_host?

            expectation = "expect(Integrations::Clients::HTTP).to have_received(:#{@definition.http_method}).#{count}"

            "\n\n      it '#{title}' do\n        client.verify_token(valid_token)\n\n        #{expectation}\n      end"
          end

          # Generated clients switch on the status code only, so the stubbed response needs no body.
          def stub_host_helper
            return '' unless @definition.multi_host?

            <<~RUBY
              def stub_host(endpoint, code:)
                host_response = instance_double(Net::HTTPResponse, code: code)
                allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).with(endpoint, anything).and_return(host_response)
              end
            RUBY
          end

          # The one path that differs between hosts: once the others reject, the last host decides.
          def multi_host_examples
            return '' unless @definition.multi_host?

            <<~RUBY
              context 'when every host but the last rejects the token' do
                before do
                  described_class::API_ENDPOINTS[0...-1].each { |endpoint| stub_host(endpoint, code: '#{code_for(:inactive)}') }
                end

                it 'returns active when the last host accepts it' do
                  stub_host(described_class::API_ENDPOINTS.last, code: '#{code_for(:active)}')

                  expect(client.verify_token(valid_token).active?).to be(true)
                end

                it 'returns unknown when the last host returns an unmapped code' do
                  stub_host(described_class::API_ENDPOINTS.last, code: '#{unmapped_code}')

                  expect(client.verify_token(valid_token).unknown?).to be(true)
                end
              end
            RUBY
          end

          # An HTTP code the definition does not map, used to exercise the
          # unknown-never-inactive fallthrough.
          def unmapped_code
            mapped = @definition.compiled_status_map.keys

            Rack::Utils::HTTP_STATUS_CODES.keys.find { |code| mapped.exclude?(code) }
          end
        end
      end
    end
  end
end
