/**
 * Generates the `.eslint_todo/` lists. Each list exempts the files that violate one rule today, so
 * the rule only fails on new offenses.
 *
 * Usage:
 *   node scripts/frontend/generate_eslint_todo_list.mjs <rule...>         # create or update lists
 *   node scripts/frontend/generate_eslint_todo_list.mjs --all             # update every list
 *   node scripts/frontend/generate_eslint_todo_list.mjs --all --check     # fail if a list is outdated
 *
 * The files are linted with the real `eslint.config.mjs` and `REVEAL_ESLINT_TODO=1`, limited to the
 * requested rules, in a single pass.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ESLint } from 'eslint';
import { program } from 'commander';
import * as prettier from 'prettier';
import {
  addIndexExport,
  getEnabledRules,
  getListedFiles,
  groupOffendingFiles,
  keepUnparsedEntries,
  removeIndexExport,
  todoFileName,
} from './lib/eslint_todo.mjs';

const ROOT_PATH = path.resolve(import.meta.dirname, '../../');
const TODO_DIR = path.join(ROOT_PATH, '.eslint_todo');
const INDEX_PATH = path.join(TODO_DIR, 'index.mjs');
const OPTIONS_MODULE = path.join(import.meta.dirname, 'lib/eslint_todo_options.mjs');
const LINTED_EXTENSIONS = ['js', 'mjs', 'cjs', 'vue', 'graphql'];

const readIfExists = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf-8') : null);
const relative = (file) => path.relative(ROOT_PATH, file);

async function prettify(data) {
  const prettierConfig = await prettier.resolveConfig(path.join(ROOT_PATH, '.prettierrc'));
  return prettier.format(data, { ...prettierConfig, parser: 'babel' });
}

function formatTodoFile(rule, files) {
  return prettify(`
    /**
     * Generated by \`node scripts/frontend/generate_eslint_todo_list.mjs ${rule}\`.
     */
    export default {
      files: [${files.map((file) => JSON.stringify(file)).join(',\n')}],
      rules: {
        ${JSON.stringify(rule)}: 'off',
      },
    }
  `);
}

// ESLint does not read `.gitignore`, so linting `.` would also pick up local folders such as
// `.yalc/` or `.claude/worktrees/`. Lint the tracked files instead, like a CI checkout.
function listLintedFiles() {
  const output = execFileSync(
    'git',
    ['ls-files', '-z', '--', ...LINTED_EXTENSIONS.map((extension) => `*.${extension}`)],
    { cwd: ROOT_PATH, encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 },
  );
  return output.split('\0').filter((file) => file && fs.existsSync(path.join(ROOT_PATH, file)));
}

async function lint(rules, concurrency) {
  process.env.ESLINT_TODO_RULES = JSON.stringify(rules);
  process.env.ESLINT_TODO_CONCURRENCY = concurrency;
  process.env.ESLINT_TODO_ROOT = ROOT_PATH;
  const eslint = await ESLint.fromOptionsModule(pathToFileURL(OPTIONS_MODULE));
  return eslint.lintFiles(listLintedFiles());
}

function reportFatalErrors(fatalErrors) {
  console.error(
    `ESLint could not parse ${fatalErrors.length} files, so their todo entries are kept as they are:`,
  );
  for (const { file, message } of fatalErrors.slice(0, 10)) {
    console.error(`  ${file}: ${message.replace(/\s+/g, ' ').slice(0, 200)}`);
  }
  if (fatalErrors.some(({ file }) => file.endsWith('.graphql'))) {
    console.error('If the GraphQL schema failed to load, run `./scripts/dump_graphql_schema`.');
  }
}

/**
 * @returns {Promise<{ file: string, content: string | null }[]>} The files to write, with `null`
 *   for the ones to delete.
 */
async function planChanges(rules, { offendingFiles, listedFiles, unparsedFiles }) {
  const todoFiles = await Promise.all(
    rules.map(async (rule) => {
      const file = path.join(TODO_DIR, todoFileName(rule));
      const files = keepUnparsedEntries(
        offendingFiles.get(rule),
        listedFiles.get(rule) ?? [],
        unparsedFiles,
      );
      console.log(`${rule}: ${files.length} offending files.`);
      const content = files.length > 0 ? await formatTodoFile(rule, files) : null;
      return { rule, file, current: readIfExists(file), content };
    }),
  );

  const changes = todoFiles
    .filter(({ current, content }) => content !== current)
    .map(({ file, content }) => ({ file, content }));

  const currentIndex = fs.readFileSync(INDEX_PATH, 'utf-8');
  const index = todoFiles.reduce(
    (acc, { rule, content }) =>
      content === null ? removeIndexExport(acc, rule) : addIndexExport(acc, rule),
    currentIndex,
  );
  if (index !== currentIndex) changes.push({ file: INDEX_PATH, content: await prettify(index) });
  return changes;
}

function applyChanges(changes) {
  for (const { file, content } of changes) {
    if (content === null) {
      console.log(`Deleting ${relative(file)}.`);
      fs.rmSync(file);
    } else {
      console.log(`Writing ${relative(file)}.`);
      fs.writeFileSync(file, content);
    }
  }
}

function reportOutdated(changes) {
  if (changes.length === 0) {
    console.log('All todo lists are up to date.');
    return;
  }
  console.error('These todo lists are outdated:');
  for (const { file, content } of changes) {
    console.error(`  ${relative(file)}${content === null ? ' (no offenses left, delete it)' : ''}`);
  }
  console.error(
    'Run `node scripts/frontend/generate_eslint_todo_list.mjs --all` and commit the result.',
  );
  process.exitCode = 1;
}

async function main() {
  program
    .description('Generates the .eslint_todo/ lists of files that currently violate a rule.')
    .argument('[rules...]', 'the rules to generate a todo list for')
    .option('--all', 'regenerate the todo list of every rule in .eslint_todo/index.mjs')
    .option('--check', 'do not write anything, and fail if a todo list would change')
    .option('--concurrency <value>', 'number of linting threads, "auto", or "off"', 'off')
    .parse();
  const options = program.opts();

  // `eslint.config.mjs` reads this when it is imported, so set it before loading the config.
  process.env.REVEAL_ESLINT_TODO = '1';

  const listedFiles = getListedFiles(await import('../../.eslint_todo/index.mjs'));
  const rules = [...new Set([...(options.all ? listedFiles.keys() : []), ...program.args])];
  if (rules.length === 0) {
    program.error('Pass at least one rule, or --all.');
  }

  const { default: eslintConfig } = await import('../../eslint.config.mjs');
  const enabledRules = getEnabledRules(eslintConfig);
  // Rules from existing lists are not checked: a list whose rule was disabled has no offenses left,
  // so it gets deleted.
  const unknownRules = program.args.filter((rule) => !enabledRules.has(rule));
  if (unknownRules.length > 0) {
    program.error(
      `These rules are not enabled in eslint.config.mjs: ${unknownRules.join(', ')}. Enable them before generating a todo list.`,
    );
  }

  console.log(`Linting for ${rules.length} rules...`);
  const results = await lint(rules, options.concurrency);
  const { offendingFiles, fatalErrors } = groupOffendingFiles(results, rules, ROOT_PATH);

  if (fatalErrors.length > 0) reportFatalErrors(fatalErrors);

  const unparsedFiles = new Set(fatalErrors.map(({ file }) => file));
  const changes = await planChanges(rules, { offendingFiles, listedFiles, unparsedFiles });
  if (options.check) {
    reportOutdated(changes);
  } else {
    applyChanges(changes);
  }
  // Offenses in unparsed files are unknown, so the lists cannot be confirmed up to date.
  if (fatalErrors.length > 0) process.exitCode = 1;
}

main();
